"""가상 데이터 생성. 실데이터로 교체 시 이 파일은 사용하지 않음.
센터명·수치 전부 가상."""
import random, pandas as pd
from pathlib import Path
OUT = Path(__file__).parent / "sample_data"; OUT.mkdir(exist_ok=True)
random.seed(7)
CENTERS = [f"센터{chr(65+i)}" for i in range(12)]   # 센터A~L

# 1) 센터 현황
pd.DataFrame({"센터명": CENTERS, "지역": random.choices(["수도권","영남","호남","충청","강원","제주"], k=12),
              "운영기관": [f"운영기관{i+1}" for i in range(12)], "개소일": ["2024-03-01"]*6 + ["2025-03-01"]*6,
              "등록 학생 수": [random.randint(80, 220) for _ in CENTERS]}).to_excel(OUT/"센터현황_2026.xlsx", index=False)

# 2) 등원율 — 같은 기준일(2026-06-30), 산출 시점 다른 두 버전
base = {c: round(random.uniform(55, 92), 1) for c in CENTERS}
july = pd.DataFrame({"지표명": "등원율", "센터명": CENTERS, "기준일": "2026-06-30", "값": [base[c] for c in CENTERS],
                     "지표 정의": "월 등원일수 ÷ 운영일수 × 100", "집계기간": "2026-06-01~2026-06-30",
                     "추출시점": "2026-07-03", "원자료 버전": "출결 v1"})
july.to_excel(OUT/"등원율_2026-06-30기준_7월제출본.xlsx", index=False)
sept = july.copy()
sept["추출시점"] = "2026-09-10"; sept["원자료 버전"] = "출결 v2(사후 보정)"
for c in ["센터C", "센터G", "센터K"]:                      # 세 센터만 사후 보정으로 값 변경
    sept.loc[sept["센터명"] == c, "값"] = round(base[c] + random.choice([-3.2, 2.1, 1.4]), 1)
sept.to_excel(OUT/"등원율_2026-06-30기준_9월재산출.xlsx", index=False)

